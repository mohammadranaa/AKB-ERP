#!/usr/bin/env node
// Copies db/migrations/*.sql into apps/api/src/cli/migrations.embedded.ts so a bundled API
// (Vercel) can run migrations without the db folder on disk. A test checks the copy matches.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'db', 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const entries = files.map((f) => `  [${JSON.stringify(f)}, ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))}]`).join(',\n');
const out = `// Generated by tools/embed-migrations.mjs from db/migrations. Do not edit; run the script instead.\nexport const EMBEDDED_MIGRATIONS: [name: string, sql: string][] = [\n${entries}\n];\n`;
writeFileSync(join(root, 'apps/api/src/cli/migrations.embedded.ts'), out);
console.log(`embedded ${files.length} migrations`);
